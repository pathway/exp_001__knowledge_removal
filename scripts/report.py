"""Build docs/results_tables.md from runs/*.jsonl (pilot runs excluded). No API calls."""
import _cli  # noqa: F401
from collections import defaultdict

from kr import store
from kr.config import ROOT, RUNS
from kr.items import select
from kr.metrics import chance_acc
from kr.summary import column, table

STEPS = (0, 5, 10, 15, 20)


def final_eval(records):
    return [r for r in records if "eval" in r][-1]["eval"]


def eval_at(records, step):
    return next(r["eval"] for r in records if r.get("step") == step and "eval" in r)


def main():
    facts = store.facts()
    forget_b = select(facts, "forget", "B")
    exp1, exp2 = defaultdict(list), defaultdict(list)
    for path in sorted(RUNS.glob("*__exp*.jsonl")):
        header, records = store.read_run(path)
        if "unlearn" in header:
            exp2[(header["unlearn"]["args"]["method"], header["args"]["attack"])].append(records)
        else:
            exp1[header["args"]["method"]].append(records)

    out = ["# exp_001 result tables", "",
           "Generated by `scripts/report.py` from `runs/*.jsonl`. Mean ± sample sd over seeds. "
           "acc = right surname in greedy text; leak = any forget-set surname; mc = multiple choice "
           "vs 3 distractors (chance 0.25); chance = permutation baseline for acc.", ""]

    groups = ("forget_A", "forget_B", "retain_near_B", "retain_far_B")
    # step 0 of every exp-1 run is the base model on the known facts (LoRA starts at zero)
    named = [("base = step 0", [r for runs in exp1.values() for r in runs], lambda r: eval_at(r, 0))]
    named += [(m, runs, final_eval) for m, runs in exp1.items()]
    rows = []
    for method, runs, pick in named:
        evs = [pick(r) for r in runs]
        rows.append([f"{method} (n={len(runs)})"]
                    + [f"{column(evs, lambda e: e[g]['acc'])} / {column(evs, lambda e: e[g]['mc'])}" for g in groups]
                    + [column(evs, lambda e: e["probes"]["all"]),
                       column(evs, lambda e: e["forget"]["leak"])])
    out += ["## Exp 1: unlearning, final step (30). Cells: acc / mc", "",
            table(["method", *groups, "probes", "forget leak"], rows), ""]

    rows = []
    for (method, attack), runs in sorted(exp2.items()):
        evs = [final_eval(r) for r in runs]
        chance = [chance_acc(forget_b, [e["generations"][f.id] for f in forget_b]) for e in evs]
        rows.append([method, attack, f"{len(runs)}",
                     column(evs, lambda e: e["forget_A"]["acc"]),
                     column(evs, lambda e: e["forget_B"]["acc"]),
                     column(chance, lambda c: c),
                     column(evs, lambda e: e["forget_B"]["mc"]),
                     column(evs, lambda e: e["forget_B"]["leak"]),
                     column(evs, lambda e: e["retain_near_B"]["acc"]),
                     column(evs, lambda e: e["probes"]["all"])])
    out += ["## Exp 2: recovery attacks, final step (20). Forget B was never in the attack data", "",
            table(["unlearned by", "attack", "n", "forget A acc", "**forget B acc**", "B chance",
                   "forget B mc", "forget B leak", "retain-near B acc", "probes"], rows), ""]

    rows = []
    for (method, attack), runs in sorted(exp2.items()):
        if attack == "relearn_A":
            rows.append([method] + [column([eval_at(r, s) for r in runs], lambda e: e["forget_B"]["acc"]) for s in STEPS])
    out += ["## Exp 2: forget B acc during relearn_A", "",
            table(["unlearned by", *[f"step {s}" for s in STEPS]], rows), ""]

    usd = sum(store.read_run(p)[1][-1].get("usd", 0) for p in RUNS.glob("*.jsonl"))
    out += [f"Spend of the runs in this table (our token count): ${usd:.2f}", ""]
    (ROOT / "docs" / "results_tables.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
